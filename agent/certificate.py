"""
The certificate: the report, written for a person.

report.json is the machine-readable evidence; the certificate is the same
content as a plain-text page an officer can read, print or file. It is
rendered *deterministically* from the report (nothing in it is generated by
a model), so anyone can re-render it from report.json and compare. The
report records the SHA-256 of the certificate, and both files get their own
OpenPGP signature:

    report.json      report.json.asc
    certificate.txt  certificate.txt.asc
"""

from __future__ import annotations

import textwrap
from typing import Any

from .pgp import format_fingerprint

WIDTH = 78


def inr(amount: int | float | None) -> str:
    """Rs. 12,34,567 -- Indian digit grouping."""
    if amount is None:
        return "n/a"
    s = str(int(round(amount)))
    if len(s) <= 3:
        return f"Rs. {s}"
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return "Rs. " + ",".join(groups + [tail])


def _wrap(text: str, indent: int = 0, first: str = "") -> str:
    pad = " " * indent
    return textwrap.fill(text, WIDTH, initial_indent=first or pad, subsequent_indent=pad, break_long_words=False,
                         break_on_hyphens=False)


def _rule(title: str) -> str:
    return f"\n{title}\n{'-' * len(title)}"


MARK = {"pass": "PASS", "warn": "ATTN", "fail": "FAIL", "skipped": "SKIP"}


def render(report: dict[str, Any]) -> str:
    """The certificate text for `report`. Ignores the report's own `certificate` field."""
    v, val = report["verdict"], report["validator"]
    parcel = report.get("parcel") or {}
    q = report.get("quality") or {}
    prov = report.get("provenance") or {}
    out = ["LANDCHAIN  -  VALIDATION CERTIFICATE", "Evidence only. This certificate approves and rejects nothing.", ""]
    rows = [("Report", report["reportId"]), ("Application", report["applicationId"]),
            ("Parcel", f"{report['surveyNo']}  ({parcel.get('village')}, {parcel.get('district')}; "
                       f"{parcel.get('areaSqm')} sq.m)"),
            ("Seller", report["parties"]["seller"]["name"]), ("Buyer", report["parties"]["buyer"]["name"]),
            ("Consideration", inr(report["considerationINR"])), ("Written", report["generatedAt"]),
            ("Validator", f"{val['name']} ({val['mspId']}, role {val['role']})"),
            ("Signing key", format_fingerprint(val["pgpFingerprint"]))]
    out += [f"{k:<14}{v_}" for k, v_ in rows]

    c = report["checks"]
    out.append(_rule(f"VERDICT: {v['status'].upper()}"))
    out.append(_wrap(f"{v['failed']} failed, {v['attention']} need attention, {v['passed']} passed, "
                     f"{v['skipped']} not run, of {len(c)} checks. Confidence {v['confidence']}."))
    out.append(_wrap("Rule: " + v["rule"] + ". The verdict is computed by this rule, never by the language model."))

    out.append(_rule("CHECKS"))
    for ch in sorted(c, key=lambda x: ("fail", "warn", "skipped", "pass").index(x["status"])):
        out.append(_wrap(ch["label"], 7, f"[{MARK[ch['status']]}] "))
        if ch["status"] != "pass":
            out.append(_wrap(ch["detail"], 7))
            out += [_wrap(e, 11, "     - ") for e in ch["evidence"][:6]]
    inv = report.get("investigation") or {}
    if inv.get("ran"):
        out.append(_rule("THE AI INVESTIGATION (THE MODEL CHOSE THESE STEPS)"))
        out.append(_wrap(f"{inv.get('calls', 0) if isinstance(inv.get('calls'), int) else len(inv.get('calls', []))} read-only "
                         f"tool call(s) in {len(inv.get('turns', []))} turn(s) by {inv.get('model') or 'the model'}; "
                         f"stopped: {inv.get('stop')}."))
        for call in inv.get("calls", []) if isinstance(inv.get("calls"), list) else []:
            args = ", ".join(f"{k}={v}" for k, v in (call.get("args") or {}).items())
            out.append(_wrap(f"{call['id']} {call['name']}({args}){'' if call.get('ok') else '  -- failed'}", 7, "  "))
        for f_ in inv.get("findings", []):
            out.append(_wrap(f_["claim"] + f"  [{', '.join(f_['evidence'])}]", 11,
                             "  CONCERN  " if f_["severity"] == "concern" else "  info     "))
        for f_ in inv.get("refused", []):
            out.append(_wrap(f"{f_['claim']} -- refused: {'; '.join(f_['refusedBecause'])}", 11, "  REFUSED  "))
    out.append(_rule("EXPLANATION FOR THE REVENUE OFFICER"))
    out.append(_wrap(report["explanation"]["officer"]))
    out.append(_rule("EXPLANATION SHOWN TO THE CITIZEN"))
    out.append(_wrap(report["explanation"]["citizen"]))

    out.append(_rule("HOW WELL THE WRITING STICKS TO THE EVIDENCE"))
    for who in ("officer", "citizen"):
        h = (q.get("hallucination") or {}).get(who)
        g = (q.get("generation") or {}).get(who) or {}
        if h:
            s = h["scores"]
            writer = g.get("writer", "?") + (f", {g['model']}" if g.get("model") else "")
            out.append(_wrap(f"{who:<8} faithfulness {s['faithfulness']:.2f}   hallucination rate "
                             f"{s['hallucinationRate']:.2f}   {'passed' if h['passed'] else 'FAILED'}   "
                             f"written by {writer}; model drafts: {g.get('drafts', 0)}", 9))
    inj = q.get("promptInjection") or {}
    out.append(_wrap(f"Instruction-like text found in documents: {inj.get('hits', 0)}."))
    out.append(_wrap("Scores are recomputed from the text above and the facts by anyone running agent/verifier.py."))

    out.append(_rule("HOW THIS WAS MADE"))
    out.append(_wrap(f"Pipeline: {prov.get('graph', {}).get('name', 'validator')} on LangGraph "
                     f"{prov.get('libraries', {}).get('langgraph', '?')}, {len(prov.get('graph', {}).get('nodes', []))} steps."))
    out.append(_wrap(f"Facts SHA-256 {prov.get('factsSha256', '?')}"))
    out.append(_wrap(f"Prompt templates SHA-256 {prov.get('promptTemplateSha256', '?')}"))
    out.append(_wrap(f"Reasoning trace {report['reasoningTraceCID']}"))

    out.append(_rule("HOW TO VERIFY"))
    out += [_wrap("Save the validator's public key as landchain-validator.asc, then:"),
            "    gpg --import landchain-validator.asc",
            "    gpg --verify report.json.asc report.json",
            "    gpg --verify certificate.txt.asc certificate.txt",
            "    sha256sum report.json      # equals the hash anchored on the ledger",
            "    python -m agent.verifier report.json report.json.asc landchain-validator.asc",
            "", _wrap(report["notice"])]
    return "\n".join(out) + "\n"
